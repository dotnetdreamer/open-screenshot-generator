#!/usr/bin/env node
// Writes src/lib/growth/worldShapes.ts: the countries of the world as SVG
// paths, for the map on Growth's Today screen.
//
// The shapes are Natural Earth's (public domain) as world-atlas packs them
// (ISC). Neither package is a dependency of the app: the paths are worked out
// once here and the result is checked in, so the app ships no map library.
// To run it again, install the four packages into a folder of their own and
// pass that folder:
//
//   npm install --prefix /tmp/map-deps --ignore-scripts world-atlas@2 topojson-client@3 d3-geo@3 i18n-iso-countries@7
//   node scripts/gen-world-map.mjs /tmp/map-deps
//
// Countries come from the 1:110m file. Storefronts too small for that file
// (Singapore, Malta, Bahrain and the like) are a dot at the centre of their
// 1:50m shape, so every App Store country can show on the map.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const depsDir = process.argv[2];
if (!depsDir) {
  console.error('Pass the folder the map packages were installed into.');
  process.exit(1);
}
const require = createRequire(path.join(path.resolve(depsDir), 'node_modules', 'noop.js'));
const { feature } = require('topojson-client');
const { geoNaturalEarth1, geoPath, geoCentroid } = await import(pathToModule('d3-geo'));
const countries = require('i18n-iso-countries');

function pathToModule(name) {
  return 'file://' + require.resolve(name);
}

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WIDTH = 960;

function read(name) {
  return JSON.parse(readFileSync(require.resolve(`world-atlas/${name}`), 'utf8'));
}

/** ISO 3166-1 alpha-2 for a world-atlas feature, or null for land with no code (Northern Cyprus, Somaliland). */
function codeOf(item) {
  const name = item.properties?.name;
  if (name === 'Kosovo') return 'XK';
  if (!item.id || item.id === '-99') return null;
  return countries.numericToAlpha2(item.id) ?? null;
}

const small = read('countries-110m.json');
const medium = read('countries-50m.json');
const land = feature(small, small.objects.countries).features.filter((item) => codeOf(item) !== 'AQ');

// Fit the land without Antarctica, so the map spends no room on it.
const projection = geoNaturalEarth1().fitWidth(WIDTH, { type: 'FeatureCollection', features: land });
const draw = geoPath(projection);
const [[, top], [, bottom]] = draw.bounds({ type: 'FeatureCollection', features: land });
projection.translate([projection.translate()[0], projection.translate()[1] - top + 4]);
const height = Math.ceil(bottom - top + 8);

/** A path with every number rounded to one decimal, which is a tenth of a pixel at this size. */
function compact(d) {
  return d
    .replace(/-?\d+\.\d+/g, (number) => String(Math.round(Number(number) * 10) / 10))
    .replace(/,/g, ' ')
    .replace(/ -/g, '-');
}

const shapes = {};
const unnamed = [];
for (const item of land) {
  const d = draw(item);
  if (!d) continue;
  const code = codeOf(item);
  if (code) shapes[code] = (shapes[code] ? `${shapes[code]}` : '') + compact(d);
  else unnamed.push(compact(d));
}

const dots = {};
for (const item of feature(medium, medium.objects.countries).features) {
  const code = codeOf(item);
  if (!code || code === 'AQ' || shapes[code]) continue;
  const point = projection(geoCentroid(item));
  if (!point || !Number.isFinite(point[0])) continue;
  dots[code] = [Math.round(point[0] * 10) / 10, Math.round(point[1] * 10) / 10];
}

const header = `// Generated by scripts/gen-world-map.mjs. Do not edit by hand.
//
// The countries of the world as SVG paths in a ${WIDTH} x ${height} box (Natural
// Earth projection), keyed by ISO 3166-1 alpha-2, for the map on Growth's
// Today screen. \`dots\` are countries too small to draw at this size, as the
// centre of each one. \`land\` is land that has no country code.
//
// Shapes: Natural Earth 1:110m and 1:50m Admin 0 countries, public domain
// (naturalearthdata.com), by way of world-atlas:
//
// Copyright 2013-2019 Michael Bostock
//
// Permission to use, copy, modify, and/or distribute this software for any purpose
// with or without fee is hereby granted, provided that the above copyright notice
// and this permission notice appear in all copies.
//
// THE SOFTWARE IS PROVIDED "AS IS" AND THE AUTHOR DISCLAIMS ALL WARRANTIES WITH
// REGARD TO THIS SOFTWARE INCLUDING ALL IMPLIED WARRANTIES OF MERCHANTABILITY AND
// FITNESS. IN NO EVENT SHALL THE AUTHOR BE LIABLE FOR ANY SPECIAL, DIRECT,
// INDIRECT, OR CONSEQUENTIAL DAMAGES OR ANY DAMAGES WHATSOEVER RESULTING FROM LOSS
// OF USE, DATA OR PROFITS, WHETHER IN AN ACTION OF CONTRACT, NEGLIGENCE OR OTHER
// TORTIOUS ACTION, ARISING OUT OF OR IN CONNECTION WITH THE USE OR PERFORMANCE OF
// THIS SOFTWARE.
`;

const body = `
export const WORLD_WIDTH = ${WIDTH};
export const WORLD_HEIGHT = ${height};

export const WORLD_SHAPES: Record<string, string> = ${JSON.stringify(shapes, null, 0).replace(/","/g, '",\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, ',\n}')};

export const WORLD_DOTS: Record<string, [number, number]> = ${JSON.stringify(dots).replace(/\],"/g, '],\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, ',\n}')};

export const WORLD_LAND: string[] = ${JSON.stringify(unnamed)};
`;

const out = path.join(repo, 'src/lib/growth/worldShapes.ts');
writeFileSync(out, header + body);
console.log(`Wrote ${path.relative(repo, out)}: ${Object.keys(shapes).length} countries, ${Object.keys(dots).length} dots, ${unnamed.length} unnamed, ${WIDTH}x${height}, ${(header.length + body.length) / 1000} kB`);
